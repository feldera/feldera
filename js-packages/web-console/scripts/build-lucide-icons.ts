// Generates `feldera-theme/fd.css`: one `.fd-<name>` class for every `fd-<name>`
// used in the sources. Each class draws the Lucide icon `<name>` as a CSS mask, so it
// takes the size of `font-size` and the colour of `color`, like a font icon.
// Run `bun run build-icons` after you use a new `fd-<name>` class.

import fs from 'node:fs/promises'
import path from 'node:path'
import { Glob } from 'bun'

// The stroke width of every icon, in units of the 24x24 icon grid. Lucide's default is 2.
const STROKE_WIDTH = 1.5

const webConsoleDir = path.resolve(import.meta.dir, '..')
const lucideDir = path.join(webConsoleDir, 'node_modules/lucide-static/icons')
// Icons that Lucide does not have, drawn in the Lucide format.
const customDir = path.join(webConsoleDir, 'src/assets/icons/custom')
const jsPackagesDir = path.resolve(webConsoleDir, '..')
// In feldera-theme, so that every app that uses the shared components can load the icons.
const outputFile = path.join(jsPackagesDir, 'feldera-theme/fd.css')
const sourceGlobs = [
  'web-console/src/**/*.{svelte,ts,js,css}',
  'profiler-app/src/**/*.{svelte,ts,js,css}',
  'profiler-layout/src/**/*.{svelte,ts,js,css}',
  'common-ui/src/**/*.{svelte,ts,js,css}'
]

// Class names that differ from the Lucide icon name.
const lucideNameOf: Record<string, string> = {
  more_horiz: 'ellipsis'
}

const findUsedIconNames = async () => {
  const names = new Set<string>()
  for (const pattern of sourceGlobs) {
    for await (const file of new Glob(pattern).scan(jsPackagesDir)) {
      const absoluteFile = path.join(jsPackagesDir, file)
      if (absoluteFile === outputFile) {
        continue
      }
      const text = await fs.readFile(absoluteFile, 'utf8')
      // This scan cannot see a name built at runtime, so its icon would be missing.
      if (/\bfd-\$?\{/.test(text)) {
        throw new Error(`${file}: write each fd-<name> class in full, not as fd-{...}`)
      }
      for (const match of text.matchAll(/\bfd-([a-z0-9_-]*[a-z0-9_])/g)) {
        names.add(match[1])
      }
    }
  }
  return [...names].sort()
}

const readIconSvg = async (name: string) => {
  for (const file of [
    path.join(customDir, `${name}.svg`),
    path.join(lucideDir, `${lucideNameOf[name] ?? name}.svg`)
  ]) {
    const svg = await fs.readFile(file, 'utf8').catch(() => undefined)
    if (svg !== undefined) {
      return svg
    }
  }
  return undefined
}

// A mask uses only the alpha channel, so the stroke colour does not matter.
const toMaskDataUrl = (svg: string) => {
  const minified = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[^>]*>/, (rootTag) => rootTag.replace(/\s(class|width|height)="[^"]*"/g, ''))
    .replace(/stroke-width="[^"]*"/g, `stroke-width="${STROKE_WIDTH}"`)
    .replace(/currentColor/g, 'black')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim()
  return `url("data:image/svg+xml,${minified.replace(/"/g, "'").replace(/[<>#%]/g, encodeURIComponent)}")`
}

const names = await findUsedIconNames()
const missing: string[] = []
const iconRules: string[] = []
for (const name of names) {
  const svg = await readIconSvg(name)
  if (svg === undefined) {
    missing.push(name)
    continue
  }
  iconRules.push(`.fd-${name} {\n  --fd-icon: ${toMaskDataUrl(svg)};\n}`)
}
if (missing.length > 0) {
  console.error(`No Lucide or custom icon for: ${missing.map((n) => `fd-${n}`).join(', ')}`)
  process.exit(1)
}

const css = `/* Generated by web-console/scripts/build-lucide-icons.ts. Do not edit. */

.fd {
  line-height: 1;
}

.fd::before {
  content: "";
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: top;
  background-color: currentColor;
  mask: var(--fd-icon) center / contain no-repeat;
}

${iconRules.join('\n\n')}
`
await fs.writeFile(outputFile, css)
console.log(`Generated ${iconRules.length} icons in ${path.relative(jsPackagesDir, outputFile)}`)
