    static List<OptimizerStep> referenceOrder(boolean outputsAreSets, boolean incrementalize) {
        return REFERENCE_ORDER.stream().filter(step -> switch (step) {
            case EnsureDistinctOutputs -> outputsAreSets;
            case Incrementalize, NoIntegral -> incrementalize;
            default -> true;
        }).toList();
    }
