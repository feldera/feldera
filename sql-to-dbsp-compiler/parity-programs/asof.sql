CREATE TABLE l (k BIGINT NOT NULL, ts BIGINT NOT NULL LATENESS 0);
CREATE TABLE r (k BIGINT NOT NULL, ts BIGINT NOT NULL LATENESS 0);
CREATE LOCAL VIEW matched AS SELECT l.k, l.ts AS lts, r.ts AS rts
FROM l LEFT ASOF JOIN r MATCH_CONDITION(l.ts >= r.ts) ON l.k = r.k;
CREATE VIEW counts AS SELECT rts, COUNT(*) AS n FROM matched GROUP BY rts;
