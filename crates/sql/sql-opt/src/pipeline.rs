//! Top-level circuit optimizer order. Each occurrence creates a fresh pass instance.
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
pub enum OptimizerStep {
    UdfInliner,
    DecomposeExpensiveFilters,
    ImplementNow,
    Lineage,
    DeterministicFunctions,
    NoConnectorMetadata,
    StopOnError,
    RecursiveComponents,
    PruneUnusedInputs,
    EnsureDistinctOutputs,
    PropagateConstants,
    PropagateEmptySources,
    MergeSums,
    CreateStarJoins,
    RemoveNoops,
    OptimizeProjectionsOnce,
    FuseExpensiveMaps,
    RemoveIntermediateViews,
    LeftJoinChains,
    UnusedFields,
    RemoveUselessLeftJoins,
    Cse,
    FuseIntoArrayAgg,
    ExpandAggregates,
    ExpandAggregateZero,
    RemoveStarJoins,
    DeadCode,
    OptimizeDistinct,
    OptimizeIncremental,
    Incrementalize,
    RemoveIAfterD,
    Simplify,
    RemoveConstantFilters,
    OptimizeProjection,
    PullFilter,
    OptimizeOnlyProjections,
    ShareIndexes,
    ShareWindowIntegrals,
    FilterJoin,
    ShareOutputIntegrators,
    MonotoneAnalyzer,
    RemoveErrorTable,
    CloneOperatorsWithFanout,
    LinearPostprocessRetainKeys,
    ExpandIndexedInputs,
    FindUnboundedState,
    InsertWeightValidation,
    NoIntegral,
    ExpandHop,
    RemoveDeindexOperators,
    RemoveIdentityOperators,
    ChainVisitor,
    OptimizeProjections,
    SimplifyWaterline,
    ValidateRecursiveOperators,
    LowerAsof,
    LowerCircuit,
    AdjustSqlIndex,
    BalancedJoins,
    ImplementChains,
    ExpandCasts,
    SimplifyConditionals,
    ImplementJoins,
    RemoveAllViews,
    PushDifferentialsUp,
    InnerCse,
    CreateRuntimeErrorWrappers,
    StrayGc,
    CanonicalForm,
    ConstantViews,
    StaticDeclarations,
    CheckHints,
    ComparatorDeclarations,
    Gen2Passes,
    CompactNames,
    MerkleHashes,
    TagRegions,
    CircuitStatistics,
}

#[derive(Clone, Copy, Deserialize)]
pub struct PipelineOptions {
    pub outputs_are_sets: bool,
    pub incrementalize: bool,
}

/// Runtime conditions such as Gen-2 and star-join metadata are evaluated by
/// their observed conditional pass, which occupies a slot for either outcome.
pub fn optimizer_order(options: PipelineOptions) -> impl Iterator<Item = OptimizerStep> {
    use OptimizerStep::*;
    [
        UdfInliner,
        // Expose fields to temporal filters before lowering NOW().
        DecomposeExpensiveFilters,
        ImplementNow,
        Lineage,
        DeterministicFunctions,
        NoConnectorMetadata,
        StopOnError,
        RecursiveComponents,
        PruneUnusedInputs,
        EnsureDistinctOutputs,
        PropagateConstants,
        PropagateEmptySources,
        MergeSums,
        CreateStarJoins,
        RemoveNoops,
        OptimizeProjectionsOnce,
        FuseExpensiveMaps,
        RemoveIntermediateViews,
        LeftJoinChains,
        UnusedFields,
        RemoveUselessLeftJoins,
        Cse,
        // Fuse aggregates with maps before expanding them.
        FuseIntoArrayAgg,
        ExpandAggregates,
        ExpandAggregateZero,
        RemoveStarJoins,
        DeadCode,
        PropagateEmptySources,
        OptimizeDistinct,
        // Recursive circuits also need this simplification in snapshot mode.
        OptimizeIncremental,
        DeadCode,
        Incrementalize,
        OptimizeIncremental,
        RemoveIAfterD,
        DeadCode,
        Simplify,
        RemoveConstantFilters,
        // Constant-false filters now have empty inputs.
        PropagateEmptySources,
        OptimizeProjection,
        PullFilter,
        OptimizeOnlyProjections,
        ShareIndexes,
        // Window sharing needs common operators after projections have been fused.
        Cse,
        ShareWindowIntegrals,
        // Fusing joins with filters improves the precision of waterlines.
        FilterJoin,
        // Share join integrals before monotonicity separates the ones needed by GC.
        ShareOutputIntegrators,
        MonotoneAnalyzer,
        // The error table is needed through monotonicity analysis.
        RemoveErrorTable,
        CloneOperatorsWithFanout,
        LinearPostprocessRetainKeys,
        ExpandIndexedInputs,
        // Unbounded-state analysis needs GC operators and primary-key indexes.
        FindUnboundedState,
        InsertWeightValidation,
        FilterJoin,
        DeadCode,
        Simplify,
        NoIntegral,
        ExpandHop,
        RemoveDeindexOperators,
        RemoveNoops,
        RemoveIdentityOperators,
        ChainVisitor,
        OptimizeProjections,
        // Fuse aggregates with joins after unused columns have been removed.
        FuseIntoArrayAgg,
        SimplifyWaterline,
        Simplify,
        Cse,
        ValidateRecursiveOperators,
        LowerAsof,
        LowerCircuit,
        AdjustSqlIndex,
        BalancedJoins,
        ChainVisitor,
        ImplementChains,
        ExpandCasts,
        SimplifyConditionals,
        Simplify,
        ImplementJoins,
        RemoveAllViews,
        PushDifferentialsUp,
        Cse,
        InnerCse,
        CreateRuntimeErrorWrappers,
        StrayGc,
        // Normalize expressions before computing persistent IDs.
        CanonicalForm,
        ConstantViews,
        // Classic emits static constants. Gen-2 keeps closures self-contained.
        StaticDeclarations,
        CheckHints,
        ComparatorDeclarations,
        // Hash the final graph for the selected engine.
        Gen2Passes,
        CompactNames,
        MerkleHashes,
        TagRegions,
        CircuitStatistics,
    ]
    .into_iter()
    .filter(move |step| match step {
        EnsureDistinctOutputs => options.outputs_are_sets,
        Incrementalize | NoIntegral => options.incrementalize,
        _ => true,
    })
}
