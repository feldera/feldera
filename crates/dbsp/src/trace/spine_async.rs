impl<B> Trace for Spine<B>
where
    B: Batch,
{
    type Batch = B;

    fn new(factories: &B::Factories, name: Arc<String>, role: TraceRole) -> Self {
        Self::with_runtime(
            Runtime::runtime()
                .expect("Attempting to create a spine merger outside of a DBSP runtime"),
            Runtime::worker_index(),
            factories,
            name,
            role,
        )
    }

    fn set_name(&mut self, name: Arc<String>) {
        self.merger.state.lock().unwrap().name = name;
    }

    fn fork(&self) -> Self {
        // Take the name, role, frontier, filters, and batches under a single
        // lock acquisition, so that the fork sees a consistent view even if a
        // background merge completes concurrently.  The filters come from
        // the locked state, rather than from `self.key_filter` and
        // `self.value_filter`, because the locked copies are what the
        // source's merges actually enforce.
        let (name, role, frontier, (key_filter, value_filter), batches) = {
            let state = self.merger.state.lock().unwrap();
            (
                state.name.clone(),
                state.role,
                state.frontier.clone(),
                state.get_filters(),
                state.get_batches(),
            )
        };

        let mut fork = Self::with_runtime(
            Runtime::runtime().expect("Attempting to fork a spine outside of a DBSP runtime"),
            Runtime::worker_index(),
            &self.factories,
            name,
            role,
        );

        if let Some(filter) = key_filter {
            fork.retain_keys(filter);
        }
        if let Some(filter) = value_filter {
            fork.retain_values(filter);
        }
        fork.merger.set_frontier(&frontier);

        for batch in batches {
            fork.insert_without_blocking(batch);
        }

        // `insert_without_blocking` marks the fork dirty; the fork must
        // instead inherit the source's flag, so set it last.
        fork.dirty = self.dirty;

        fork
    }

    fn set_frontier(&mut self, frontier: &B::Time) {
        self.merger.set_frontier(frontier)
    }

    fn frontier(&self) -> B::Time {
        self.merger.state.lock().unwrap().frontier.clone()
    }

    fn exert(&mut self, _effort: &mut isize) {}

    fn consolidate(self) -> Option<B> {
        // A batch `Arc` can be shared outside this spine, e.g., with a
        // [`SpineSnapshot`] or a [`Trace::fork`] of this spine, in which case
        // `Arc::unwrap_or_clone` copies the batch instead of taking ownership.
        let batches = self.merger.pause().into_iter().map(Arc::unwrap_or_clone);
        let result = merge_batches(
            &self.factories,
            batches,
            &self.key_filter,
            &self.value_filter,
        );
        if result.is_empty() {
            None
        } else {
            Some(result)
        }
    }

    async fn insert(&mut self, batch: impl Into<Arc<Self::Batch>>) {
        let batch =
            Self::maybe_flush_batch(Runtime::runtime().as_ref(), batch, &self.factories, || {
                self.merger.state.lock().unwrap().get_filters()
            });
        if !batch.is_empty() {
            self.dirty = true;
            if self
                .merger
                .add_batch(batch, false)
                .count_loose_batches()
                .should_apply_backpressure()
            {
                self.merger.backpressure_wait().await;
            }
        }
    }

    /// Inserts a batch into the spine without blocking.  Thus, this omits:
    ///
    /// - Spilling the batch to storage when that is a good idea.  The caller
    ///   may do this beforehand by calling [Spine::maybe_flush_batch].
    ///
    /// - Waiting until the number of batches in the spine falls below the level
    ///   at which we impose backpressure.  The function returns true if
    ///   backpressure is warranted.  The caller may do so afterward by calling
    ///   [Spine::backpressure_wait].
    fn insert_without_blocking(&mut self, batch: impl Into<Arc<B>>) -> bool {
        let batch = batch.into();
        if !batch.is_empty() {
            self.dirty = true;
            self.merger
                .add_batch(batch, false)
                .count_loose_batches()
                .should_apply_backpressure()
        } else {
            false
        }
    }

    /// Waits for the number of batches in the spine to fall below the level at
    /// which we impose backpressure.
    async fn backpressure_wait(&self) {
        self.merger.backpressure_wait().await;
    }

    fn clear_dirty_flag(&mut self) {
        self.dirty = false;
    }

    fn dirty(&self) -> bool {
        self.dirty
    }

    fn retain_keys(&mut self, filter: Filter<Self::Key>) {
        self.merger.set_key_filter(&filter);
        self.key_filter = Some(filter);
    }

    fn retain_values(&mut self, filter: GroupFilter<Self::Val>) {
        self.merger.set_value_filter(&filter);
        self.value_filter = Some(filter);
    }

    fn key_filter(&self) -> &Option<Filter<Self::Key>> {
        &self.key_filter
    }

    fn value_filter(&self) -> &Option<GroupFilter<Self::Val>> {
        &self.value_filter
    }

    fn save(&mut self, persistent_id: &str) -> Result<Box<dyn OperatorCheckpoint>, Error> {
        Ok(Box::new(SpineOperatorCheckpoint {
            persistent_id: persistent_id.into(),
            batches: self.get_batches(),
            dirty: self.dirty,
        }))
    }

    fn restore(&mut self, base: &StoragePath, persistent_id: &str) -> Result<(), Error> {
        let pspine_path = Self::checkpoint_file(base, persistent_id);

        let content = Runtime::storage_backend().unwrap().read(&pspine_path)?;
        let archived = rkyv::check_archived_root::<CommittedSpine>(&content).map_err(|e| {
            crate::circuit::checkpointer::checkpoint_invalid_data_error(
                "Spine checkpoint validation failed",
                format!("{pspine_path}: {e}"),
            )
        })?;

        let committed: CommittedSpine = archived
            .deserialize(&mut Deserializer::default())
            .map_err(|e| {
                crate::circuit::checkpointer::checkpoint_invalid_data_error(
                    "Spine checkpoint deserialize failed",
                    format!("{pspine_path}: {e:?}"),
                )
            })?;
        self.dirty = committed.dirty;
        self.key_filter = None;
        self.value_filter = None;
        // Also clear the merger's copies of the filters, which would
        // otherwise keep filtering merges: `self.key_filter` and
        // `self.value_filter` must always mirror the locked state (`fork`
        // documents that the locked copies are authoritative).
        {
            let mut state = self.merger.state.lock().unwrap();
            state.key_filter = None;
            state.value_filter = None;
        }
        for batch in committed.batches {
            let batch =
                B::from_path(&self.factories.clone(), &batch.clone().into()).map_err(|error| {
                    crate::circuit::checkpointer::checkpoint_invalid_data_error(
                        "Spine batch read failed",
                        format!("{batch}: {error}"),
                    )
                })?;
            self.insert_without_blocking(batch);
        }

        Ok(())
    }

    fn metadata(&self, meta: &mut OperatorMeta) {
        self.merger.metadata(meta);
    }

    fn initiate_compaction(&self) {
        self.merger.initiate_compaction();
    }

    fn is_compaction_complete(&self) -> bool {
        self.merger.is_compaction_complete()
    }
}

/// A snapshot of a [Spine] ready to be written to a checkpoint.
pub struct SpineOperatorCheckpoint<B> {
    /// Persistent ID provided to [Spine::save].
    persistent_id: String,
    /// The batches that will go into the checkpoint.
    batches: Vec<Arc<B>>,
    /// Dirty flag.
    dirty: bool,
}

impl<B> OperatorCheckpoint for SpineOperatorCheckpoint<B>
where
    B: Batch,
{
    fn write(
        self: Box<Self>,
        base: &StoragePath,
    ) -> Result<SmallVec<[Arc<dyn FileCommitter>; 1]>, Error> {
        // Persist all the batches and collect their names.
        let (ids, mut files): (Vec<_>, SmallVec<_>) = self
            .batches
            .iter()
            .map(|batch| {
                let file = batch.file_reader().unwrap_or_else(|| {
                    let persisted = batch
                        .persisted()
                        .expect("The batch should have been persisted");
                    persisted
                        .file_reader()
                        .expect("The persisted batch should be readable")
                });
                (file.path().to_string(), file as Arc<dyn FileCommitter>)
            })
            .unzip();

        // Write the spine in the form that we will restore from.
        let backend = Runtime::storage_backend().unwrap();
        let committed_spine = CommittedSpine {
            batches: ids,
            merged: Vec::new(),
            effort: 0,
            dirty: self.dirty,
        };
        let as_bytes = to_bytes(&committed_spine).expect("Serializing CommittedSpine should work.");
        files.push(backend.write(
            &Spine::<B>::checkpoint_file(base, &self.persistent_id),
            as_bytes,
        )?);

        // Write the batches in a form that `Checkpointer` can read without the
        // need to know the exact Spine type.
        let pspine_batches = PSpineBatches {
            files: committed_spine.batches,
        };
        files.push(backend.write_json(
            &Spine::<B>::batchlist_file(base, &self.persistent_id),
            &pspine_batches,
        )?);

        Ok(files)
    }
}

impl<B> Debug for SpineOperatorCheckpoint<B> {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        f.debug_struct("SpineOperatorCheckpoint")
            .field("persistent_id", &self.persistent_id)
            .field("dirty", &self.dirty)
            .finish_non_exhaustive()
    }
}

impl<B> Spine<B>
where
    B: Batch,
{
    /// Given a batch size figure out which level it should reside in.
    fn size_to_level(batch: &B, max_level0_batch_size_records: usize, merge: bool) -> usize {
        debug_assert_eq!(MAX_LEVELS, 9);
        debug_assert!(max_level0_batch_size_records > 0 && max_level0_batch_size_records <= 99_999);

        let len = batch.len();

        let effective_len = if merge {
            // Merge batches with many negative weights more aggressively. Negative updates are likely to cancel
            // out during merging. Every time this happens, two records are eliminated from the spine, speeding
            // up lookups and reducing the spine's storage footprint. Furthermore, this avoids performance anomalies
            // where an operator spends a lot of time skipping over 0-weight records.
            //
            // We implement this heuristic by accounting each record with a negative weight as N records when calculating
            // the batch's effective length (N is equal to negative_weight_multiplier() + 1). This should push such batches
            // to the next level more eagerly, until they get merged with batches that contain matching positive-weight
            // records.
            //
            // We only apply this heuristic to merged batches to avoid reordering insertions and deletions by pushing
            // deletions to higher levels than the insertions they correspond to.
            let negative_weight_count = batch.negative_weight_count().unwrap_or(0) as usize;
            len + negative_weight_count * (negative_weight_multiplier() as usize)
        } else {
            len
        };

        if effective_len <= max_level0_batch_size_records {
            return 0;
        }
        match effective_len {
            0..=99_999 => 1,
            100_000..=999_999 => 2,
            1_000_000..=9_999_999 => 3,
            10_000_000..=99_999_999 => 4,
            100_000_000..=999_999_999 => 5,
            1_000_000_000..=9_999_999_999 => 6,
            10_000_000_000..=99_999_999_999 => 7,
            _ => 8, // For reference: 100 bln * 8 bytes ~= 750 GiB
        }
    }

    /// Allocates a new `Spine` for `worker_index` in `runtime`, for `role`.
    ///
    /// In the common case, [Spine::new] uses the current thread's runtime and
    /// worker index.
    pub fn with_runtime(
        runtime: Runtime,
        worker_index: usize,
        factories: &B::Factories,
        name: Arc<String>,
        role: TraceRole,
    ) -> Self {
        Spine {
            factories: factories.clone(),
            dirty: false,
            key_filter: None,
            value_filter: None,
            merger: AsyncMerger::new(runtime, worker_index, factories, name, role),
        }
    }

    /// The role this spine was built with.
    pub fn role(&self) -> TraceRole {
        self.merger.state.lock().unwrap().role
    }

    pub fn complete_merges(&mut self) {
        let batches = self.merger.pause();
        let batch = merge_batches(
            &self.factories,
            batches.into_iter().map(|b| Arc::unwrap_or_clone(b)),
            &self.key_filter,
            &self.value_filter,
        );
        self.merger.resume(vec![Arc::new(batch)]);
    }

    /// Returns `batch`, first pushing it to storage if it exceeds the
    /// user-configured `min_storage_bytes` or if we're under high memory
    /// pressure.
    pub fn maybe_flush_batch<F>(
        runtime: Option<&Runtime>,
        batch: impl Into<Arc<B>>,
        factories: &B::Factories,
        filters: F,
    ) -> Arc<B>
    where
        F: FnOnce() -> (Option<Filter<B::Key>>, Option<GroupFilter<B::Val>>),
    {
        let batch = batch.into();
        if batch.location() == BatchLocation::Memory
            && pick_insert_destination(runtime, &batch) == BatchLocation::Storage
        {
            let _span = Span::new("eager spill")
                .with_category("Spine")
                .with_tooltip(|| {
                    format!(
                        "Eagerly spill {} batch with {} keys and {} values",
                        HumanBytes::from(batch.approximate_byte_size()),
                        batch.key_count(),
                        batch.len()
                    )
                });
            match Arc::try_unwrap(batch) {
                Ok(mut batch) => {
                    let builder =
                        B::Builder::for_merge(factories, [&batch], Some(BatchLocation::Storage));
                    let (key_filter, value_filter) = filters();
                    Arc::new(ListMerger::merge(
                        factories,
                        builder,
                        vec![batch.consuming_cursor(key_filter, value_filter)],
                    ))
                }
                Err(batch) => {
                    let batch_ref: &B = &batch;
                    let builder =
                        B::Builder::for_merge(factories, [batch_ref], Some(BatchLocation::Storage));
                    let (key_filter, value_filter) = filters();
                    Arc::new(ListMerger::merge(
                        factories,
                        builder,
                        vec![batch.merge_cursor(key_filter, value_filter)],
                    ))
                }
            }
        } else {
            batch
        }
    }

    /// Returns an object that can be used to wait for backpressure to be
    /// relieved.  Returns `None` if no backpressure is needed.
    ///
    /// Pass the report half to [`Self::record_backpressure_wait`] after
    /// awaiting, so the wait shows up in
    /// `merge_backpressure_wait_time_seconds` and in profiles.
    pub(crate) fn backpressure_waiter(
        &self,
    ) -> Option<(
        impl Future<Output = ()> + Send + use<B>,
        BackpressureWaitReport,
    )> {
        self.merger.backpressure_waiter().map(|wait| wait.split())
    }

    /// Reports a wait obtained from [`Self::backpressure_waiter`].
    pub(crate) fn record_backpressure_wait(&self, report: BackpressureWaitReport) {
        self.merger.record_backpressure_wait(report)
    }
}

